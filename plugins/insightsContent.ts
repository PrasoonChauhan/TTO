import fs from 'node:fs'
import path from 'node:path'
import YAML from 'yaml'
import { Marked } from 'marked'
import type { Plugin, ViteDevServer } from 'vite'
import { TOPICS, SITE_URL } from '../src/content/topics.ts'

/**
 * Insights engine. One Markdown file per article in content/insights/.
 *
 *   virtual:insights          article metadata + authors (for lists and headers)
 *   virtual:insight-bodies    { slug: () => import(body) }, one lazy chunk per article
 *   insights/<slug>/index.html  generated page per article, with SEO tags and the
 *                               article text baked in for crawlers (gitignored)
 *   sitemap.xml + robots.txt  emitted at build time
 *
 * Files starting with "_" and README.md are ignored.
 */

const ROOT = path.resolve(import.meta.dirname, '..')
const DIR = path.join(ROOT, 'content/insights')
const AUTHORS = path.join(ROOT, 'content/authors.yml')
const OUT = path.join(ROOT, 'insights')
const GENERATED_MARK = '<!-- generated by plugins/insightsContent.ts: do not edit -->'
const FRONTMATTER = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/
const TOPIC_IDS = TOPICS.map((t) => t.id) as string[]

const LIST = 'virtual:insights'
const BODIES = 'virtual:insight-bodies'
const BODY = 'virtual:insight/'

type Author = { name: string; role?: string; photo?: string; bio?: string; linkedin?: string }
type Heading = { id: string; text: string; level: number }
type Article = {
  file: string
  slug: string
  title: string
  excerpt: string
  topic: string
  date: string
  updated?: string
  author: string
  tags: string[]
  cover?: string
  coverAlt?: string
  featured: boolean
  takeaways: string[]
  seoTitle?: string
  seoDescription?: string
  minutes: number
  words: number
  toc: Heading[]
  html: string
}

const fail = (file: string, msg: string): never => {
  throw new Error(`[insights] content/insights/${file}: ${msg}`)
}
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/<[^>]+>/g, '')
    .replace(/&[a-z]+;/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
const isDate = (s: unknown) => typeof s === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(s)

function readAuthors(): Record<string, Author> {
  if (!fs.existsSync(AUTHORS)) return {}
  return YAML.parse(fs.readFileSync(AUTHORS, 'utf8')) ?? {}
}

/** Markdown to HTML with heading anchors, figures, safe external links. */
function render(md: string) {
  const toc: Heading[] = []
  const used = new Set<string>()
  const marked = new Marked({
    gfm: true,
    renderer: {
      heading({ tokens, depth }) {
        const inner = this.parser.parseInline(tokens)
        if (depth === 1) depth = 2 // the page title is the only h1
        let id = slugify(inner) || 'section'
        while (used.has(id)) id += '-2'
        used.add(id)
        if (depth <= 3) toc.push({ id, text: inner.replace(/<[^>]+>/g, ''), level: depth })
        return `<h${depth} id="${id}">${inner}</h${depth}>\n`
      },
      link({ href, title, tokens }) {
        const text = this.parser.parseInline(tokens)
        const external = /^https?:\/\//.test(href) && !href.startsWith(SITE_URL)
        const t = title ? ` title="${esc(title)}"` : ''
        return `<a href="${esc(href)}"${t}${external ? ' target="_blank" rel="noopener noreferrer"' : ''}>${text}</a>`
      },
      image({ href, title, text }) {
        const cap = title ? `<figcaption>${esc(title)}</figcaption>` : ''
        return `<figure><img src="${esc(href)}" alt="${esc(text)}" loading="lazy" decoding="async" />${cap}</figure>`
      },
    },
  })
  const html = marked.parse(md) as string
  return { html, toc }
}

function readAll(): { articles: Article[]; authors: Record<string, Author> } {
  const authors = readAuthors()
  if (!fs.existsSync(DIR)) return { articles: [], authors }
  const files = fs
    .readdirSync(DIR)
    .filter((f) => f.endsWith('.md') && !f.startsWith('_') && f.toLowerCase() !== 'readme.md')

  const articles = files.map((file): Article => {
    const raw = fs.readFileSync(path.join(DIR, file), 'utf8')
    const m = raw.match(FRONTMATTER)
    if (!m) fail(file, 'missing the --- frontmatter block at the top of the file.')
    let d: Record<string, any>
    try {
      d = YAML.parse(m![1]) ?? {}
    } catch (e) {
      fail(file, `frontmatter is not valid YAML. ${(e as Error).message}`)
    }
    for (const k of ['title', 'excerpt', 'topic', 'date', 'author']) if (!d![k]) fail(file, `"${k}" is required.`)
    if (!TOPIC_IDS.includes(d!.topic)) fail(file, `"topic" must be one of: ${TOPIC_IDS.join(', ')}.`)
    if (!isDate(d!.date)) fail(file, '"date" must look like 2026-10-12.')
    if (d!.updated && !isDate(d!.updated)) fail(file, '"updated" must look like 2026-10-12.')
    if (!authors[d!.author]) fail(file, `author "${d!.author}" is not in content/authors.yml.`)
    const body = m![2].trim()
    if (!body) fail(file, 'the article body is empty.')

    const { html, toc } = render(body)
    const words = body.replace(/[#>*_`\[\]()!-]/g, ' ').split(/\s+/).filter(Boolean).length
    return {
      file,
      slug: d!.slug || file.replace(/\.md$/, ''),
      title: d!.title,
      excerpt: d!.excerpt,
      topic: d!.topic,
      date: d!.date,
      updated: d!.updated,
      author: d!.author,
      tags: Array.isArray(d!.tags) ? d!.tags : [],
      cover: d!.cover,
      coverAlt: d!.coverAlt,
      featured: d!.featured === true,
      takeaways: Array.isArray(d!.takeaways) ? d!.takeaways : [],
      seoTitle: d!.seoTitle,
      seoDescription: d!.seoDescription,
      minutes: Math.max(1, Math.round(words / 220)),
      words,
      toc,
      html,
    }
  })
  articles.sort((a, b) => b.date.localeCompare(a.date))
  return { articles, authors }
}

/* ---------- Generated article pages ---------- */

function pageHtml(a: Article, author: Author) {
  const url = `${SITE_URL}/insights/${a.slug}/`
  const title = `${a.seoTitle ?? a.title} | The Third Orbit Insights`
  const desc = a.seoDescription ?? a.excerpt
  const topic = TOPICS.find((t) => t.id === a.topic)!
  const image = a.cover ? `${SITE_URL}${a.cover}` : undefined
  const ld = [
    {
      '@context': 'https://schema.org',
      '@type': 'Article',
      headline: a.title,
      description: desc,
      datePublished: a.date,
      dateModified: a.updated ?? a.date,
      author: { '@type': author.name === 'The Third Orbit' ? 'Organization' : 'Person', name: author.name },
      publisher: { '@type': 'Organization', name: 'The Third Orbit', url: SITE_URL },
      mainEntityOfPage: url,
      articleSection: topic.label,
      keywords: a.tags.join(', '),
      wordCount: a.words,
      ...(image ? { image } : {}),
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Insights', item: `${SITE_URL}/insights/` },
        { '@type': 'ListItem', position: 2, name: topic.label, item: `${SITE_URL}/insights/?topic=${topic.id}` },
        { '@type': 'ListItem', position: 3, name: a.title, item: url },
      ],
    },
  ]
  return `<!doctype html>
${GENERATED_MARK}
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <link rel="icon" type="image/png" href="/logos/tto_black_monogram.png" />
    <meta name="theme-color" content="#F4F4F5" />
    <title>${esc(title)}</title>
    <meta name="description" content="${esc(desc)}" />
    <link rel="canonical" href="${url}" />
    <meta property="og:type" content="article" />
    <meta property="og:site_name" content="The Third Orbit" />
    <meta property="og:title" content="${esc(a.title)}" />
    <meta property="og:description" content="${esc(desc)}" />
    <meta property="og:url" content="${url}" />
    ${image ? `<meta property="og:image" content="${image}" />` : ''}
    <meta property="article:published_time" content="${a.date}" />
    <meta property="article:section" content="${esc(topic.label)}" />
    <meta name="twitter:card" content="${image ? 'summary_large_image' : 'summary'}" />
    <meta name="twitter:title" content="${esc(a.title)}" />
    <meta name="twitter:description" content="${esc(desc)}" />
    <noscript><style>.article-static { opacity: 1 !important; }</style></noscript>
    <script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>
  </head>
  <body data-slug="${a.slug}">
    <div id="root">
      <!-- Pre-rendered for search engines and no-JS readers; replaced when the page loads. -->
      <main class="article-static">
        <article>
          <p>${esc(topic.label)}</p>
          <h1>${esc(a.title)}</h1>
          <p>${esc(a.excerpt)}</p>
          <p>${esc(author.name)} · <time datetime="${a.date}">${a.date}</time> · ${a.minutes} min read</p>
          ${a.html}
        </article>
      </main>
    </div>
    <script type="module" src="/src/article.tsx"></script>
  </body>
</html>
`
}

/** Writes insights/<slug>/index.html for every article and removes stale ones. */
function writePages(articles: Article[], authors: Record<string, Author>) {
  fs.mkdirSync(OUT, { recursive: true })
  const keep = new Set(articles.map((a) => a.slug))
  for (const name of fs.readdirSync(OUT)) {
    const file = path.join(OUT, name, 'index.html')
    if (!keep.has(name) && fs.existsSync(file) && fs.readFileSync(file, 'utf8').includes(GENERATED_MARK)) {
      fs.rmSync(path.join(OUT, name), { recursive: true })
    }
  }
  const inputs: Record<string, string> = {}
  for (const a of articles) {
    const dir = path.join(OUT, a.slug)
    fs.mkdirSync(dir, { recursive: true })
    const file = path.join(dir, 'index.html')
    const next = pageHtml(a, authors[a.author])
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== next) fs.writeFileSync(file, next)
    inputs[`insight-${a.slug}`] = file
  }
  return inputs
}

function sitemap(articles: Article[]) {
  const today = new Date().toISOString().slice(0, 10)
  const urls = [
    { loc: '/', lastmod: today, priority: '1.0' },
    { loc: '/about/', lastmod: today, priority: '0.8' },
    { loc: '/work/', lastmod: today, priority: '0.8' },
    { loc: '/insights/', lastmod: articles[0]?.date ?? today, priority: '0.8' },
    ...articles.map((a) => ({ loc: `/insights/${a.slug}/`, lastmod: a.updated ?? a.date, priority: '0.7' })),
  ]
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${SITE_URL}${u.loc}</loc><lastmod>${u.lastmod}</lastmod><priority>${u.priority}</priority></url>`).join('\n')}
</urlset>
`
}

export function insightsContent(): Plugin {
  let server: ViteDevServer | undefined
  let data = readAll()

  const refresh = (file: string) => {
    const p = path.resolve(file)
    if (!server || (!p.startsWith(DIR) && p !== AUTHORS)) return
    try {
      data = readAll()
      writePages(data.articles, data.authors)
    } catch (e) {
      server.config.logger.error((e as Error).message)
      return
    }
    for (const mod of server.moduleGraph.idToModuleMap.values()) {
      if (mod.id?.startsWith('\0virtual:insight')) server.moduleGraph.invalidateModule(mod)
    }
    server.ws.send({ type: 'full-reload' })
  }

  return {
    name: 'tto-insights-content',
    config() {
      data = readAll()
      const inputs = writePages(data.articles, data.authors)
      return { build: { rollupOptions: { input: inputs } } }
    },
    resolveId(id) {
      if (id === LIST || id === BODIES || id.startsWith(BODY)) return '\0' + id
    },
    load(id) {
      if (!id.startsWith('\0virtual:insight')) return
      for (const f of fs.existsSync(DIR) ? fs.readdirSync(DIR) : []) this.addWatchFile(path.join(DIR, f))
      if (fs.existsSync(AUTHORS)) this.addWatchFile(AUTHORS)
      if (id === '\0' + LIST) {
        const meta = data.articles.map(({ html: _html, ...rest }) => rest)
        return `export const articles = ${JSON.stringify(meta)};\nexport const authors = ${JSON.stringify(data.authors)};`
      }
      if (id === '\0' + BODIES) {
        const entries = data.articles.map((a) => `  ${JSON.stringify(a.slug)}: () => import(${JSON.stringify(BODY + a.slug)}),`)
        return `export default {\n${entries.join('\n')}\n}`
      }
      const slug = id.slice(('\0' + BODY).length)
      const a = data.articles.find((x) => x.slug === slug)
      return `export default ${JSON.stringify({ html: a?.html ?? '' })}`
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'sitemap.xml', source: sitemap(data.articles) })
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n` })
    },
    configureServer(s) {
      server = s
      s.watcher.add([DIR, AUTHORS])
      s.watcher.on('add', refresh)
      s.watcher.on('change', refresh)
      s.watcher.on('unlink', refresh)
    },
  }
}
